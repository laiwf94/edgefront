//! The decision service's protobuf code is generated from the vendored
//! `proto/` files and checked in under `src/service/proto/`, so no build
//! needs protoc or a build script. This test is the build step: it compiles
//! the vendored files with protox (a protobuf compiler in Rust), generates
//! the code with prost-build at the versions pinned in the workspace, and
//! fails if the result differs from what is checked in by a single byte.
//!
//! After changing a file under `proto/` or a generator pin, regenerate with
//! `make proto`, which runs this test with `EDGEFRONT_REGENERATE_PROTO=1` to
//! write the files instead of comparing them.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// The vendored files the service compiles; their imports come along.
const ROOTS: &[&str] = &["envoy/service/ratelimit/v3/rls.proto"];

/// The banner on every generated file.
const BANNER: &str = "// Generated by crates/edgefront-limiter/tests/proto_codegen.rs from\n\
// crates/edgefront-limiter/proto. Do not edit: change the .proto files and run\n\
// `make proto`.\n\n";

fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn checked_in_dir() -> PathBuf {
    crate_dir().join("src/service/proto")
}

/// Every file prost-build writes for the vendored protos, by file name.
fn generate() -> BTreeMap<String, String> {
    let proto = crate_dir().join("proto");
    let files = protox::compile(ROOTS, [&proto]).expect("the vendored protos compile");
    let out = std::env::temp_dir().join(format!("edgefront-proto-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    fs::create_dir_all(&out).unwrap();
    prost_build::Config::new()
        // The well-known types (Duration, Struct, Timestamp, the wrappers)
        // are generated here too, rather than taken from prost-types, so the
        // limiter depends on prost alone.
        .compile_well_known_types()
        .out_dir(&out)
        .compile_fds(files)
        .expect("prost-build generates the code");
    let mut generated = BTreeMap::new();
    for entry in fs::read_dir(&out).unwrap() {
        let path = entry.unwrap().path();
        // envoy.type.v3 is written as envoy.r#type.v3.rs, a raw identifier
        // that has no place in a file name.
        let name = path
            .file_name()
            .unwrap()
            .to_str()
            .unwrap()
            .replace("r#", "");
        let code = fs::read_to_string(&path).unwrap();
        generated.insert(name, format!("{BANNER}{code}"));
    }
    fs::remove_dir_all(&out).unwrap();
    generated
}

fn checked_in(dir: &Path) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    for entry in fs::read_dir(dir).expect("src/service/proto exists") {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_str().unwrap().to_owned();
        // The hand-written module tree is not generated.
        if name.ends_with(".rs") && name.matches('.').count() > 1 {
            files.insert(name, fs::read_to_string(&path).unwrap());
        }
    }
    files
}

#[test]
fn regenerating_gives_identical_code() {
    let generated = generate();
    let dir = checked_in_dir();
    if std::env::var_os("EDGEFRONT_REGENERATE_PROTO").is_some() {
        for (name, _) in checked_in(&dir) {
            if !generated.contains_key(&name) {
                fs::remove_file(dir.join(&name)).unwrap();
            }
        }
        for (name, code) in &generated {
            fs::write(dir.join(name), code).unwrap();
        }
        return;
    }
    let existing = checked_in(&dir);
    let generated_names: Vec<_> = generated.keys().collect();
    let existing_names: Vec<_> = existing.keys().collect();
    assert_eq!(
        existing_names, generated_names,
        "the generated files differ from those in src/service/proto: run `make proto`"
    );
    for (name, code) in &generated {
        if existing[name] != *code {
            let line = existing[name]
                .lines()
                .zip(code.lines())
                .position(|(a, b)| a != b)
                .map_or_else(|| "the length".to_owned(), |n| format!("line {}", n + 1));
            panic!(
                "src/service/proto/{name} differs from the generator at {line}: run `make proto`"
            );
        }
    }
}

#[test]
fn every_vendored_proto_is_compiled() {
    // A file under proto/ that nothing imports would be vendored for nothing.
    let proto = crate_dir().join("proto");
    let files = protox::compile(ROOTS, [&proto]).unwrap();
    let mut compiled: Vec<String> = files
        .file
        .iter()
        .filter_map(|f| f.name.clone())
        .filter(|n| !n.starts_with("google/"))
        .collect();
    compiled.sort();
    let mut vendored = Vec::new();
    let mut stack = vec![proto.clone()];
    while let Some(dir) = stack.pop() {
        for entry in fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|e| e == "proto") {
                let rel = path.strip_prefix(&proto).unwrap();
                vendored.push(rel.to_str().unwrap().to_owned());
            }
        }
    }
    vendored.sort();
    assert_eq!(compiled, vendored);
}
